import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = join(root, 'in-built', 'rank-manifest.mjs');
const serviceWorkerPath = join(root, 'public', 'sw.js');
const models = ['cl100k_base', 'o200k_base'];

function resolveRankFile(model) {
  try {
    return require.resolve(`js-tiktoken/ranks/${model}`);
  } catch (error) {
    throw new Error(`Unable to resolve js-tiktoken rank asset for ${model}: ${error.message}`);
  }
}

async function hashFile(filePath) {
  const content = await readFile(filePath);
  return createHash('sha256').update(content).digest('hex').slice(0, 16);
}

const entries = {};
for (const model of models) {
  const filePath = resolveRankFile(model);
  entries[model] = {
    id: model,
    version: await hashFile(filePath),
    model,
  };
}

const combinedVersion = createHash('sha256')
  .update(models.map((model) => `${model}:${entries[model].version}`).join('|'))
  .digest('hex')
  .slice(0, 16);

const manifestSource = `// GENERATED by scripts/generate-rank-manifest.mjs. Do not edit by hand.\nexport const CURRENT_RANK_MANIFEST = Object.freeze(${JSON.stringify(entries, null, 2)});\nexport const CURRENT_RANK_CACHE_VERSION = ${JSON.stringify(combinedVersion)};\n`;

await mkdir(dirname(manifestPath), { recursive: true });
await mkdir(dirname(serviceWorkerPath), { recursive: true });
await writeFile(manifestPath, manifestSource, 'utf8');

const serviceWorkerSource = `/* GENERATED by scripts/generate-rank-manifest.mjs. */
const CACHE_PREFIX = 'tiktoken-ranks-';
const CURRENT_CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(combinedVersion)};

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => Promise.all(
      cacheNames
        .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CURRENT_CACHE_NAME)
        .map((name) => caches.delete(name))
    )).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || !url.pathname.includes('tiktoken')) return;

  event.respondWith((async () => {
    const cache = await caches.open(CURRENT_CACHE_NAME);
    const cached = await cache.match(event.request);
    if (cached) return cached;

    const response = await fetch(event.request);
    if (response.ok) await cache.put(event.request, response.clone());
    return response;
  })());
});
`;
await writeFile(serviceWorkerPath, serviceWorkerSource, 'utf8');

console.log(`[Build Automation] Generated rank manifest: ${combinedVersion}`);
for (const model of models) console.log(`  ${model}: ${entries[model].version}`);
